/**
 * Database Migration Runner
 * Executes all SQL migrations in db/migrations/ sequentially.
 */
const fs = require('fs');
const path = require('path');
const pool = require('../src/config/db');

async function runMigrations() {
  console.log('🚀 Starting database migrations...');
  const migrationsDir = path.join(__dirname, '../db/migrations');

  if (!fs.existsSync(migrationsDir)) {
    console.error(`Migrations directory not found: ${migrationsDir}`);
    process.exit(1);
  }

  const files = fs
    .readdirSync(migrationsDir)
    .filter((f) => f.endsWith('.sql'))
    .sort();

  console.log(`Found ${files.length} migration file(s).`);

  const client = await pool.connect();

  try {
    // Check if the database has legacy bigint tables or is a fresh/UUID database
    const idTypeRes = await client.query(`
      SELECT data_type FROM information_schema.columns 
      WHERE table_name = 'tenants' AND column_name = 'id'
    `);
    const isBigIntDb = idTypeRes.rows[0]?.data_type === 'bigint';

    // Ensure migrations tracking table exists
    await client.query(`
      CREATE TABLE IF NOT EXISTS schema_migrations (
        id SERIAL PRIMARY KEY,
        filename VARCHAR(255) UNIQUE NOT NULL,
        applied_at TIMESTAMPTZ DEFAULT NOW()
      );
    `);

    for (const file of files) {
      const filePath = path.join(migrationsDir, file);
      let sql = fs.readFileSync(filePath, 'utf8');

      const alreadyApplied = await client.query(
        'SELECT 1 FROM schema_migrations WHERE filename = $1',
        [file]
      );

      if (alreadyApplied.rowCount > 0) {
        console.log(`- Skipping ${file} (already applied)`);
        continue;
      }

      // If running on an existing database with BIGINT identities, adapt references seamlessly
      if (isBigIntDb) {
        sql = sql
          .replace(/UUID PRIMARY KEY DEFAULT uuid_generate_v4\(\)/g, 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
          .replace(/UUID REFERENCES/g, 'BIGINT REFERENCES')
          .replace(/UUID/g, 'BIGINT');
      }

      console.log(`- Applying ${file}...`);
      await client.query('BEGIN');
      try {
        await client.query(sql);
        await client.query(
          'INSERT INTO schema_migrations (filename) VALUES ($1)',
          [file]
        );
        await client.query('COMMIT');
        console.log(`  ✓ ${file} applied successfully.`);
      } catch (err) {
        await client.query('ROLLBACK');
        console.error(`  ✗ Error applying ${file}:`, err.message);
        throw err;
      }
    }

    console.log('✅ All migrations applied successfully.');
  } catch (err) {
    console.error('Migration failed:', err.message);
    process.exit(1);
  } finally {
    client.release();
    await pool.end();
  }
}

if (require.main === module) {
  runMigrations();
}

module.exports = { runMigrations };

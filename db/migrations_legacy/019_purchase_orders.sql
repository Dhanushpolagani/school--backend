BEGIN;

CREATE TABLE IF NOT EXISTS purchase_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES tenants(id),
    po_number VARCHAR(50) NOT NULL,
    supplier_id BIGINT NOT NULL,
    order_date DATE NOT NULL DEFAULT CURRENT_DATE,
    expected_delivery_date DATE,
    status VARCHAR(30) NOT NULL DEFAULT 'draft'
        CHECK (status IN (
            'draft',
            'pending_approval',
            'approved',
            'ordered',
            'partially_received',
            'received',
            'cancelled'
        )),
    subtotal_amount NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (subtotal_amount >= 0),
    tax_amount NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (tax_amount >= 0),
    discount_amount NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (discount_amount >= 0),
    total_amount NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (total_amount >= 0),
    payment_terms VARCHAR(100),
    shipping_address TEXT,
    notes TEXT,
    created_by BIGINT,
    approved_by BIGINT,
    approved_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_po_tenant_number UNIQUE (tenant_id, po_number),
    CONSTRAINT uq_po_tenant_id UNIQUE (tenant_id, id),
    CONSTRAINT fk_po_supplier
        FOREIGN KEY (tenant_id, supplier_id)
        REFERENCES inventory_suppliers (tenant_id, id)
);

CREATE TABLE IF NOT EXISTS purchase_order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES tenants(id),
    purchase_order_id BIGINT NOT NULL,
    item_id BIGINT NOT NULL,
    description TEXT,
    quantity_ordered INTEGER NOT NULL CHECK (quantity_ordered > 0),
    quantity_received INTEGER NOT NULL DEFAULT 0 CHECK (quantity_received >= 0),
    unit_price NUMERIC(12,2) NOT NULL CHECK (unit_price >= 0),
    total_price NUMERIC(12,2) NOT NULL CHECK (total_price >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_po_item_tenant_id UNIQUE (tenant_id, id),
    CONSTRAINT fk_po_items_order
        FOREIGN KEY (tenant_id, purchase_order_id)
        REFERENCES purchase_orders (tenant_id, id)
        ON DELETE CASCADE,
    CONSTRAINT fk_po_items_inventory
        FOREIGN KEY (tenant_id, item_id)
        REFERENCES inventory_items (tenant_id, id)
);

CREATE INDEX IF NOT EXISTS idx_po_tenant_status
    ON purchase_orders (tenant_id, status);

CREATE INDEX IF NOT EXISTS idx_po_tenant_supplier
    ON purchase_orders (tenant_id, supplier_id);

CREATE INDEX IF NOT EXISTS idx_po_items_order
    ON purchase_order_items (tenant_id, purchase_order_id);

CREATE INDEX IF NOT EXISTS idx_po_items_item
    ON purchase_order_items (tenant_id, item_id);

COMMIT;

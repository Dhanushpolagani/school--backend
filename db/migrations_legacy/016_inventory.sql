
BEGIN;

-- 1. Inventory categories
CREATE TABLE IF NOT EXISTS inventory_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES tenants(id),
    name VARCHAR(100) NOT NULL,
    description TEXT,
    status VARCHAR(20) NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'inactive')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (tenant_id, name),
    UNIQUE (tenant_id, id)
);

-- 2. Suppliers
CREATE TABLE IF NOT EXISTS inventory_suppliers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES tenants(id),
    name VARCHAR(150) NOT NULL,
    contact_person VARCHAR(150),
    email VARCHAR(255),
    phone VARCHAR(30),
    address TEXT,
    tax_number VARCHAR(50),
    status VARCHAR(20) NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'inactive')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (tenant_id, id)
);

-- 3. Inventory items
CREATE TABLE IF NOT EXISTS inventory_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES tenants(id),
    category_id BIGINT NOT NULL,
    item_code VARCHAR(50) NOT NULL,
    name VARCHAR(150) NOT NULL,
    description TEXT,
    unit VARCHAR(30) NOT NULL DEFAULT 'piece',
    quantity_on_hand INTEGER NOT NULL DEFAULT 0
        CHECK (quantity_on_hand >= 0),
    reorder_level INTEGER NOT NULL DEFAULT 0
        CHECK (reorder_level >= 0),
    unit_cost NUMERIC(12,2) NOT NULL DEFAULT 0
        CHECK (unit_cost >= 0),
    location VARCHAR(150),
    status VARCHAR(20) NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'inactive')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (tenant_id, item_code),
    UNIQUE (tenant_id, id),
    FOREIGN KEY (tenant_id, category_id)
        REFERENCES inventory_categories(tenant_id, id)
);

-- 4. Stock movement history
CREATE TABLE IF NOT EXISTS inventory_stock_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES tenants(id),
    item_id BIGINT NOT NULL,
    movement_type VARCHAR(20) NOT NULL
        CHECK (movement_type IN ('receipt', 'issue', 'adjustment')),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_cost NUMERIC(12,2)
        CHECK (unit_cost IS NULL OR unit_cost >= 0),
    reference_number VARCHAR(100),
    remarks TEXT,
    performed_by BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    FOREIGN KEY (tenant_id, item_id)
        REFERENCES inventory_items(tenant_id, id)
);

CREATE INDEX IF NOT EXISTS idx_inventory_items_category
    ON inventory_items (tenant_id, category_id);

CREATE INDEX IF NOT EXISTS idx_inventory_items_low_stock
    ON inventory_items (tenant_id, quantity_on_hand, reorder_level)
    WHERE status = 'active';

CREATE INDEX IF NOT EXISTS idx_inventory_movements_item
    ON inventory_stock_movements (tenant_id, item_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_inventory_suppliers_status
    ON inventory_suppliers (tenant_id, status);

COMMIT;

BEGIN;

CREATE TABLE IF NOT EXISTS admission_applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES tenants(id),
    application_number VARCHAR(50) NOT NULL,
    academic_year VARCHAR(20) NOT NULL,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100),
    date_of_birth DATE NOT NULL,
    gender VARCHAR(20) NOT NULL,
    applying_class_id BIGINT,
    applying_section_id BIGINT,
    applying_class_name VARCHAR(100),
    applying_section_name VARCHAR(50),
    parent_name VARCHAR(150) NOT NULL,
    parent_relationship VARCHAR(50) NOT NULL DEFAULT 'Parent',
    parent_phone VARCHAR(30) NOT NULL,
    parent_email VARCHAR(255),
    address TEXT,
    status VARCHAR(30) NOT NULL DEFAULT 'submitted',
    review_notes TEXT,
    reviewed_by BIGINT,
    reviewed_at TIMESTAMPTZ,
    admitted_student_id BIGINT,
    created_by BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Add optional/extended fields if they don't already exist
ALTER TABLE admission_applications ADD COLUMN IF NOT EXISTS email VARCHAR(255);
ALTER TABLE admission_applications ADD COLUMN IF NOT EXISTS phone VARCHAR(30);
ALTER TABLE admission_applications ADD COLUMN IF NOT EXISTS previous_school VARCHAR(200);
ALTER TABLE admission_applications ADD COLUMN IF NOT EXISTS previous_grade VARCHAR(50);
ALTER TABLE admission_applications ADD COLUMN IF NOT EXISTS documents_submitted JSONB DEFAULT '[]'::jsonb;
ALTER TABLE admission_applications ADD COLUMN IF NOT EXISTS interview_date TIMESTAMPTZ;
ALTER TABLE admission_applications ADD COLUMN IF NOT EXISTS interview_notes TEXT;
ALTER TABLE admission_applications ADD COLUMN IF NOT EXISTS decision_date TIMESTAMPTZ;
ALTER TABLE admission_applications ADD COLUMN IF NOT EXISTS decision_remarks TEXT;

-- Constraints and indexes
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'uq_admission_tenant_app_num'
    ) THEN
        ALTER TABLE admission_applications
        ADD CONSTRAINT uq_admission_tenant_app_num UNIQUE (tenant_id, application_number);
    END IF;
END $$;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'uq_admission_tenant_id'
    ) THEN
        ALTER TABLE admission_applications
        ADD CONSTRAINT uq_admission_tenant_id UNIQUE (tenant_id, id);
    END IF;
END $$;

ALTER TABLE admission_applications DROP CONSTRAINT IF EXISTS admission_applications_status_check;
ALTER TABLE admission_applications
ADD CONSTRAINT admission_applications_status_check
CHECK (status IN (
  'submitted',
  'under_review',
  'corrections_requested',
  'shortlisted',
  'interview_scheduled',
  'approved',
  'rejected',
  'enrolled',
  'withdrawn'
));

CREATE INDEX IF NOT EXISTS idx_admissions_tenant_status
    ON admission_applications (tenant_id, status);

CREATE INDEX IF NOT EXISTS idx_admissions_tenant_class
    ON admission_applications (tenant_id, applying_class_name);

CREATE INDEX IF NOT EXISTS idx_admissions_tenant_year
    ON admission_applications (tenant_id, academic_year);

CREATE INDEX IF NOT EXISTS idx_admissions_created_at
    ON admission_applications (tenant_id, created_at DESC);

COMMIT;

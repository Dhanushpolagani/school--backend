BEGIN;

-- Add 'student' role if missing
INSERT INTO roles (name, description)
VALUES ('student', 'Student portal user')
ON CONFLICT (name) DO NOTHING;

-- Map portal user accounts to student records
CREATE TABLE IF NOT EXISTS student_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES tenants(id),
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    student_id BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_student_user_tenant_user UNIQUE (tenant_id, user_id),
    CONSTRAINT uq_student_user_tenant_student UNIQUE (tenant_id, student_id),
    CONSTRAINT fk_student_user_student
        FOREIGN KEY (tenant_id, student_id)
        REFERENCES students(tenant_id, id)
        ON DELETE CASCADE
);

-- Map portal user accounts to parent records
CREATE TABLE IF NOT EXISTS parent_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES tenants(id),
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    parent_id BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_parent_user_tenant_user_parent UNIQUE (tenant_id, user_id, parent_id)
);

-- Student leave requests submitted via Student/Parent portals
CREATE TABLE IF NOT EXISTS student_leave_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES tenants(id),
    student_id BIGINT NOT NULL,
    from_date DATE NOT NULL,
    to_date DATE NOT NULL,
    reason TEXT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'approved', 'rejected')),
    submitted_by_role VARCHAR(20) NOT NULL DEFAULT 'parent'
        CHECK (submitted_by_role IN ('parent', 'student')),
    submitted_by_user_id BIGINT NOT NULL,
    reviewed_by BIGINT,
    reviewed_at TIMESTAMPTZ,
    review_notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_student_leave_student
        FOREIGN KEY (tenant_id, student_id)
        REFERENCES students(tenant_id, id)
        ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_student_leave_tenant_status
    ON student_leave_requests (tenant_id, status);

CREATE INDEX IF NOT EXISTS idx_student_leave_student
    ON student_leave_requests (tenant_id, student_id);

COMMIT;

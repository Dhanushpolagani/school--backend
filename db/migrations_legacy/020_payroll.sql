BEGIN;

CREATE TABLE IF NOT EXISTS payroll_salary_components (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES tenants(id),
    name VARCHAR(100) NOT NULL,
    type VARCHAR(20) NOT NULL CHECK (type IN ('earning', 'deduction')),
    calculation_type VARCHAR(20) NOT NULL DEFAULT 'fixed'
        CHECK (calculation_type IN ('fixed', 'percentage')),
    percentage_of VARCHAR(50),
    default_amount_paise BIGINT NOT NULL DEFAULT 0 CHECK (default_amount_paise >= 0),
    status VARCHAR(20) NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'inactive')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_payroll_component_tenant_name UNIQUE (tenant_id, name),
    CONSTRAINT uq_payroll_component_tenant_id UNIQUE (tenant_id, id)
);

CREATE TABLE IF NOT EXISTS staff_salary_structures (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES tenants(id),
    staff_id BIGINT NOT NULL,
    basic_salary_paise BIGINT NOT NULL DEFAULT 0 CHECK (basic_salary_paise >= 0),
    components JSONB NOT NULL DEFAULT '[]'::jsonb,
    bank_name VARCHAR(100),
    bank_account_number VARCHAR(50),
    bank_ifsc VARCHAR(30),
    pan_number VARCHAR(30),
    effective_from DATE NOT NULL DEFAULT CURRENT_DATE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_staff_salary_tenant_staff UNIQUE (tenant_id, staff_id),
    CONSTRAINT uq_staff_salary_tenant_id UNIQUE (tenant_id, id),
    CONSTRAINT fk_staff_salary_staff
        FOREIGN KEY (tenant_id, staff_id)
        REFERENCES staff(tenant_id, id)
        ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS payroll_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES tenants(id),
    month INTEGER NOT NULL CHECK (month BETWEEN 1 AND 12),
    year INTEGER NOT NULL CHECK (year >= 2000),
    title VARCHAR(150) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'draft'
        CHECK (status IN ('draft', 'generated', 'approved', 'paid', 'cancelled')),
    total_staff_count INTEGER NOT NULL DEFAULT 0,
    total_gross_paise BIGINT NOT NULL DEFAULT 0 CHECK (total_gross_paise >= 0),
    total_deductions_paise BIGINT NOT NULL DEFAULT 0 CHECK (total_deductions_paise >= 0),
    total_net_paise BIGINT NOT NULL DEFAULT 0 CHECK (total_net_paise >= 0),
    processed_by BIGINT,
    processed_at TIMESTAMPTZ,
    approved_by BIGINT,
    approved_at TIMESTAMPTZ,
    payment_date DATE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_payroll_run_month_year UNIQUE (tenant_id, month, year),
    CONSTRAINT uq_payroll_run_tenant_id UNIQUE (tenant_id, id)
);

CREATE TABLE IF NOT EXISTS payslips (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES tenants(id),
    payroll_run_id BIGINT NOT NULL,
    staff_id BIGINT NOT NULL,
    payslip_number VARCHAR(50) NOT NULL,
    month INTEGER NOT NULL,
    year INTEGER NOT NULL,
    basic_paise BIGINT NOT NULL DEFAULT 0,
    gross_paise BIGINT NOT NULL DEFAULT 0,
    total_deductions_paise BIGINT NOT NULL DEFAULT 0,
    net_paise BIGINT NOT NULL DEFAULT 0,
    earnings_details JSONB NOT NULL DEFAULT '[]'::jsonb,
    deductions_details JSONB NOT NULL DEFAULT '[]'::jsonb,
    working_days INTEGER NOT NULL DEFAULT 30,
    present_days INTEGER NOT NULL DEFAULT 30,
    leave_days INTEGER NOT NULL DEFAULT 0,
    payment_status VARCHAR(20) NOT NULL DEFAULT 'unpaid'
        CHECK (payment_status IN ('unpaid', 'processing', 'paid')),
    payment_method VARCHAR(30) DEFAULT 'bank_transfer'
        CHECK (payment_method IN ('bank_transfer', 'cheque', 'cash')),
    payment_reference VARCHAR(100),
    paid_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_payslip_tenant_number UNIQUE (tenant_id, payslip_number),
    CONSTRAINT uq_payslip_tenant_run_staff UNIQUE (tenant_id, payroll_run_id, staff_id),
    CONSTRAINT uq_payslip_tenant_id UNIQUE (tenant_id, id),
    CONSTRAINT fk_payslip_payroll_run
        FOREIGN KEY (tenant_id, payroll_run_id)
        REFERENCES payroll_runs(tenant_id, id)
        ON DELETE CASCADE,
    CONSTRAINT fk_payslip_staff
        FOREIGN KEY (tenant_id, staff_id)
        REFERENCES staff(tenant_id, id)
);

CREATE INDEX IF NOT EXISTS idx_payroll_runs_tenant_year
    ON payroll_runs (tenant_id, year, month);

CREATE INDEX IF NOT EXISTS idx_payslips_tenant_staff
    ON payslips (tenant_id, staff_id, year, month);

CREATE INDEX IF NOT EXISTS idx_payslips_tenant_run
    ON payslips (tenant_id, payroll_run_id);

COMMIT;

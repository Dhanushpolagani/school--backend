BEGIN;

-- Certificate Templates table
CREATE TABLE IF NOT EXISTS certificate_templates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
    name VARCHAR(150) NOT NULL,
    certificate_type VARCHAR(50) NOT NULL,
    description TEXT,
    template_content TEXT NOT NULL,
    placeholders JSONB NOT NULL DEFAULT '[]'::jsonb,
    created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_certificate_templates_tenant_id UNIQUE (tenant_id, id)
);

CREATE INDEX IF NOT EXISTS idx_cert_templates_tenant_type
    ON certificate_templates (tenant_id, certificate_type);

CREATE INDEX IF NOT EXISTS idx_cert_templates_tenant_name
    ON certificate_templates (tenant_id, name);

-- Generated Student Certificates table
CREATE TABLE IF NOT EXISTS student_certificates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
    student_id BIGINT NOT NULL,
    template_id BIGINT NOT NULL,
    certificate_type VARCHAR(50) NOT NULL,
    certificate_number VARCHAR(100) NOT NULL,
    issue_date DATE NOT NULL DEFAULT CURRENT_DATE,
    academic_year VARCHAR(50),
    file_storage_key VARCHAR(500) NOT NULL,
    file_name VARCHAR(255) NOT NULL,
    generation_status VARCHAR(30) NOT NULL DEFAULT 'completed'
        CHECK (generation_status IN ('pending', 'completed', 'failed', 'revoked')),
    generated_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_student_certificates_tenant_number UNIQUE (tenant_id, certificate_number),
    CONSTRAINT fk_student_certificates_template
        FOREIGN KEY (tenant_id, template_id)
        REFERENCES certificate_templates(tenant_id, id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_student_certificates_student
        FOREIGN KEY (tenant_id, student_id)
        REFERENCES students(tenant_id, id)
        ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_student_certs_tenant_student
    ON student_certificates (tenant_id, student_id);

CREATE INDEX IF NOT EXISTS idx_student_certs_tenant_template
    ON student_certificates (tenant_id, template_id);

CREATE INDEX IF NOT EXISTS idx_student_certs_tenant_issue_date
    ON student_certificates (tenant_id, issue_date);

COMMIT;

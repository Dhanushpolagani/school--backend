BEGIN;

CREATE TABLE IF NOT EXISTS lms_courses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES tenants(id),
    class_id BIGINT,
    subject_id BIGINT,
    teacher_id BIGINT,
    code VARCHAR(50) NOT NULL,
    title VARCHAR(200) NOT NULL,
    description TEXT,
    academic_term VARCHAR(50),
    status VARCHAR(20) NOT NULL DEFAULT 'published'
        CHECK (status IN ('draft', 'published', 'archived')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_lms_courses_tenant_code UNIQUE (tenant_id, code),
    CONSTRAINT uq_lms_courses_tenant_id UNIQUE (tenant_id, id),
    CONSTRAINT fk_lms_course_staff
        FOREIGN KEY (tenant_id, teacher_id)
        REFERENCES staff(tenant_id, id)
        ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS lms_lessons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES tenants(id),
    course_id BIGINT NOT NULL,
    lesson_number INTEGER NOT NULL DEFAULT 1,
    title VARCHAR(200) NOT NULL,
    description TEXT,
    content_body TEXT,
    video_url TEXT,
    attachment_url TEXT,
    status VARCHAR(20) NOT NULL DEFAULT 'published'
        CHECK (status IN ('draft', 'published')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_lms_lessons_tenant_id UNIQUE (tenant_id, id),
    CONSTRAINT fk_lms_lessons_course
        FOREIGN KEY (tenant_id, course_id)
        REFERENCES lms_courses(tenant_id, id)
        ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS lms_materials (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES tenants(id),
    course_id BIGINT NOT NULL,
    title VARCHAR(200) NOT NULL,
    material_type VARCHAR(50) NOT NULL DEFAULT 'document'
        CHECK (material_type IN ('document', 'video', 'link', 'audio', 'syllabus')),
    file_url TEXT NOT NULL,
    description TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_lms_materials_tenant_id UNIQUE (tenant_id, id),
    CONSTRAINT fk_lms_materials_course
        FOREIGN KEY (tenant_id, course_id)
        REFERENCES lms_courses(tenant_id, id)
        ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS lms_assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES tenants(id),
    course_id BIGINT NOT NULL,
    title VARCHAR(200) NOT NULL,
    description TEXT,
    due_date TIMESTAMPTZ NOT NULL,
    max_marks NUMERIC(6,2) NOT NULL DEFAULT 100 CHECK (max_marks > 0),
    attachment_url TEXT,
    status VARCHAR(20) NOT NULL DEFAULT 'published'
        CHECK (status IN ('draft', 'published', 'closed')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_lms_assignments_tenant_id UNIQUE (tenant_id, id),
    CONSTRAINT fk_lms_assignments_course
        FOREIGN KEY (tenant_id, course_id)
        REFERENCES lms_courses(tenant_id, id)
        ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS lms_submissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES tenants(id),
    assignment_id BIGINT NOT NULL,
    student_id BIGINT NOT NULL,
    submission_text TEXT,
    attachment_url TEXT,
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    status VARCHAR(30) NOT NULL DEFAULT 'submitted'
        CHECK (status IN ('submitted', 'graded', 'late', 'resubmitted')),
    marks_obtained NUMERIC(6,2),
    feedback TEXT,
    graded_by BIGINT,
    graded_at TIMESTAMPTZ,

    CONSTRAINT uq_lms_submission_tenant_assgn_student
        UNIQUE (tenant_id, assignment_id, student_id),
    CONSTRAINT uq_lms_submissions_tenant_id UNIQUE (tenant_id, id),
    CONSTRAINT fk_lms_submission_assignment
        FOREIGN KEY (tenant_id, assignment_id)
        REFERENCES lms_assignments(tenant_id, id)
        ON DELETE CASCADE,
    CONSTRAINT fk_lms_submission_student
        FOREIGN KEY (tenant_id, student_id)
        REFERENCES students(tenant_id, id)
        ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_lms_courses_teacher
    ON lms_courses (tenant_id, teacher_id);

CREATE INDEX IF NOT EXISTS idx_lms_lessons_course
    ON lms_lessons (tenant_id, course_id, lesson_number);

CREATE INDEX IF NOT EXISTS idx_lms_assignments_course
    ON lms_assignments (tenant_id, course_id, due_date);

CREATE INDEX IF NOT EXISTS idx_lms_submissions_assignment
    ON lms_submissions (tenant_id, assignment_id);

CREATE INDEX IF NOT EXISTS idx_lms_submissions_student
    ON lms_submissions (tenant_id, student_id);

COMMIT;

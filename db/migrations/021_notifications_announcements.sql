BEGIN;

CREATE TABLE IF NOT EXISTS announcements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES tenants(id),
    title VARCHAR(255) NOT NULL,
    content TEXT NOT NULL,
    category VARCHAR(50) NOT NULL DEFAULT 'general'
        CHECK (category IN ('general', 'academic', 'exam', 'holiday', 'event', 'urgent', 'sports')),
    target_audience VARCHAR(50) NOT NULL DEFAULT 'all'
        CHECK (target_audience IN ('all', 'students', 'teachers', 'parents', 'staff', 'class')),
    target_class_id BIGINT,
    priority VARCHAR(20) NOT NULL DEFAULT 'medium'
        CHECK (priority IN ('low', 'medium', 'high', 'urgent')),
    attachment_url TEXT,
    published_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    expires_at TIMESTAMPTZ,
    status VARCHAR(20) NOT NULL DEFAULT 'published'
        CHECK (status IN ('draft', 'published', 'archived')),
    created_by BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_announcement_tenant_id UNIQUE (tenant_id, id)
);

CREATE TABLE IF NOT EXISTS notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES tenants(id),
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title VARCHAR(200) NOT NULL,
    message TEXT NOT NULL,
    type VARCHAR(30) NOT NULL DEFAULT 'info'
        CHECK (type IN ('info', 'success', 'warning', 'alert')),
    category VARCHAR(50) NOT NULL DEFAULT 'general',
    link VARCHAR(255),
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    read_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_notification_tenant_id UNIQUE (tenant_id, id)
);

CREATE INDEX IF NOT EXISTS idx_announcements_tenant_audience
    ON announcements (tenant_id, target_audience, status);

CREATE INDEX IF NOT EXISTS idx_announcements_published_at
    ON announcements (tenant_id, published_at DESC);

CREATE INDEX IF NOT EXISTS idx_notifications_user_read
    ON notifications (tenant_id, user_id, is_read, created_at DESC);

COMMIT;
